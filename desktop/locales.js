  const supported = Object.freeze(['zh-CN', 'en']);
  let locale = 'zh-CN';

  function normalizeLocale(value) {
    return value === 'en' || /^en(?:-|$)/i.test(String(value || '')) ? 'en' : 'zh-CN';
  }

  function t(key, values = {}) {
    let template = catalogs[locale][key] ?? key;
    if (typeof template !== 'string') template = key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(values[name] ?? ''));
  }

  function plural(key, count, values = {}) {
    const category = new Intl.PluralRules(locale).select(Number(count));
    const forms = catalogs[locale].plural?.[key];
    const template = forms?.[category] ?? forms?.other ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(name === 'count' ? count : (values[name] ?? '')));
  }

  function apply(root = document) {
    for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
    for (const [attribute, datasetKey] of [['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle'], ['placeholder', 'i18nPlaceholder']]) {
      for (const node of root.querySelectorAll(`[data-${datasetKey.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)}]`)) {
        node.setAttribute(attribute, t(node.dataset[datasetKey]));
      }
    }
  }

